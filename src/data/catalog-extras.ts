function decantFrom(
  product: Pick<
    Product,
    | "name"
    | "brand"
    | "description"
    | "gender"
    | "notes"
    | "fragranceFamily"
    | "occasions"
    | "rating"
    | "images"
    | "bestseller"
    | "intensity"
    | "intensityScore"
    | "projection"
    | "longevity"
  >,
  slug: string,
  prices: { three: number; five: number; ten?: number },
  createdAt: string,
  category: Product["category"] = "decant",
): Product {
  const sizes = [
    { label: "3 ml", volumeMl: 3, price: prices.three, stock: 22 },
    { label: "5 ml", volumeMl: 5, price: prices.five, stock: 18 },
    ...(prices.ten !== undefined
      ? [{ label: "10 ml", volumeMl: 10, price: prices.ten, stock: 11 }]
      : []),
  ];

  return {
    id: `decant-${slug}`,
    name: product.name,
    brand: product.brand,
    slug: `${slug}-decant`,
    description: product.description,
    gender: product.gender,
    category,
    type: "decant",
    price: prices.five,
    images: product.images,
    sizes,
    notes: product.notes,
    fragranceFamily: product.fragranceFamily,
    occasions: product.occasions,
    intensity: product.intensity,
    intensityScore: product.intensityScore,
    projection: product.projection,
    longevity: product.longevity,
    rating: product.rating,
    featured: false,
    bestseller: product.bestseller,
    stock: 18,
    createdAt,
  };
}

